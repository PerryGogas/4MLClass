#!/usr/bin/env python3
"""
4MLClass build script (run from the repository root):

    python3 tools/build.py

1. Writes sw.js: the offline helper (service worker) with the full list of app files,
   so the installed app works offline. The cache name changes with the content.
2. Writes 4MLClass-offline-build-<N>.html: one self-contained file with every style,
   script, font and image inlined, for computers with no internet. N is buildNo in
   assets/js/core.js.
No third-party Python packages are needed. Run it after every change, before uploading.
"""
import base64, hashlib, json, mimetypes, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

def read(p, mode='r'):
    with open(p, mode, **({} if 'b' in mode else {'encoding': 'utf-8'})) as f:
        return f.read()

def data_uri(path):
    mime = mimetypes.guess_type(path)[0] or 'application/octet-stream'
    if path.endswith('.woff2'): mime = 'font/woff2'
    if path.endswith('.svg'): mime = 'image/svg+xml'
    return 'data:%s;base64,%s' % (mime, base64.b64encode(read(path, 'rb')).decode())

def inline_css(path):
    css = read(path)
    d = os.path.dirname(path)
    def rep(m):
        ref = m.group(1).strip('\'"')
        if ref.startswith('data:') or ref.startswith('http'):
            return m.group(0)
        return 'url(' + data_uri(os.path.normpath(os.path.join(d, ref))) + ')'
    return re.sub(r'url\(([^)]+)\)', rep, css)

def safe_js(s):
    return s.replace('</script', '<\\/script').replace('<!--', '<\\!--')

def version():
    m = re.search(r"version:\s*'([^']+)'", read('assets/js/core.js'))
    return m.group(1) if m else '0.0.0'

def app_files():
    out = ['./', 'index.html', 'manifest.webmanifest']
    for base in ('assets', 'icons'):
        for dp, dn, fn in os.walk(base):
            dn.sort()
            for f in sorted(fn):
                if f.startswith('LICENSE') or f.endswith('.map') or f in ('thumbnail.png', 'screenshot-wide.png') or f == 'core-ml.js.bak':
                    continue
                out.append(os.path.join(dp, f).replace(os.sep, '/'))
    return out

def build_sw():
    files = app_files()
    h = hashlib.sha1()
    for f in files:
        if f != './':
            h.update(f.encode()); h.update(read(f, 'rb'))
    cache = '4mlclass-v' + version() + '-' + h.hexdigest()[:10]
    sw = """/* 4MLClass offline helper (generated by tools/build.py; do not edit by hand).
   Network first, so a new version on GitHub is picked up at once; the saved copy
   is used when offline. Every file is saved at install time. */
const CACHE = '%s';
const FILES = %s;
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(u => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('4mlclass-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    fetch(req, { cache: 'no-cache' }).then(res => {
      if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match(req, { ignoreSearch: true }).then(r => r || (req.mode === 'navigate' ? caches.match('./index.html') : Response.error())))
  );
});
""" % (cache, json.dumps(files, indent=2))
    with open('sw.js', 'w', encoding='utf-8', newline='\n') as f:
        f.write(sw)
    print('sw.js: %d files, cache %s' % (len(files), cache))

def build():
    core = read('assets/js/core.js')
    buildno = re.search(r"buildNo:\s*(\d+)", core).group(1)
    html = read('index.html')
    html = re.sub(r'\s*<link rel="(icon|apple-touch-icon|manifest)"[^>]*>', '', html)
    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', lambda m: '<style>' + inline_css(m.group(1)) + '</style>', html)
    html = re.sub(r'<script src="([^"]+)"></script>', lambda m: '<script>' + safe_js(read(m.group(1))) + '</script>', html)
    images = {p: data_uri(p) for p in ('assets/img/icon.svg', 'assets/img/emef-lab-logo.png')}
    lazy = {'assets/vendor/xlsx.core.min.js': read('assets/vendor/xlsx.core.min.js')}
    boot = ('<script>window.MLS_IN_BUNDLE=true;window.MLS_BASE="";window.MLS_BUNDLE_ASSETS=' + json.dumps(images) +
            ';window.MLS_BUNDLE_SCRIPTS=' + safe_js(json.dumps(lazy)) + ';</script>')
    html = html.replace('<head>', '<head>\n' + boot, 1)
    html = html.replace('<title>4MLClass |', '<title>4MLClass b%s |' % buildno, 1)
    html = html.replace('<meta name="theme-color"', '<link rel="icon" href="%s">\n  <meta name="theme-color"' % images['assets/img/icon.svg'], 1)
    out = '4MLClass-offline-build-%s.html' % buildno
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(html)
    print('%s: %.2f MB' % (out, os.path.getsize(out) / 1e6))

if __name__ == '__main__':
    build_sw()
    build()
